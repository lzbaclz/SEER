"""eE analyze — LAP WCET grouped bar across (arch × backend × batch).

Reads every ``lap_wcet_*.json`` produced by :mod:`seer.lap.wcet` under
``results/``, builds a Patrick / ADSLab style grouped bar of
(P50 / P99 / P99.9) inference latency in microseconds with a horizontal
WCET budget line at 200 µs, and writes both ``wcet.pdf`` (paper) and
``wcet_table.tex``.

Layout:
* x-axis = "(arch, backend, batch)" tuples, ordered slowest first so
  the most-emphasised TRT row sits on the right.
* y-axis = log10 µs (helps both small TRT bars and large BlockTransformer
  bars share a panel).
* P50 / P99 / P99.9 are 3 hatched grouped bars (white / mid-gray /
  dark gray on the baselines, light orange / orange / deep orange on
  the TinyMLP-TRT row that we defend in §6.7).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

_REPO = Path(__file__).resolve().parents[2]
if str(_REPO) not in sys.path:
    sys.path.insert(0, str(_REPO))

from seer import figstyle  # noqa: E402


def _arch_from_tag(tag: str) -> str:
    if "block_transformer" in tag:
        return "BlockTransformer"
    if "block_rnn" in tag:
        return "BlockRNN"
    if "tiny_mlp" in tag:
        return "TinyMLP"
    return "?"


def _backend_from_tag(tag: str) -> str:
    if "trt_fp16" in tag:
        return "TRT-fp16"
    if "trt" in tag:
        return "TRT"
    if "onnx" in tag:
        return "ONNX"
    if "torch" in tag:
        return "torch"
    return "?"


def _device_label(tag: str) -> str:
    """Distinguish the two A100 cards on the same host (card0 default,
    card1 for the cross-card asymmetry probe). Only TRT measurements have
    been taken on card1 so the table stays compact."""
    return "A100\\#1" if "card1" in tag else "A100"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("results_dir")
    ap.add_argument("--budget_us", type=float, default=200.0,
                    help="Per-paper WCET budget; drawn as a horizontal line.")
    ap.add_argument("--no_plot", action="store_true")
    args = ap.parse_args()

    rdir = Path(args.results_dir)
    files = sorted(rdir.glob("lap_wcet_*.json"))
    if not files:
        raise SystemExit(f"no lap_wcet_*.json under {rdir}")

    rows = []
    for f in files:
        with open(f) as fh:
            d = json.load(fh)
        rows.append({
            "tag": f.stem,
            "arch": _arch_from_tag(f.stem),
            "backend": _backend_from_tag(f.stem),
            "device": d.get("device"),
            "card": "card1" if "card1" in f.stem else "card0",
            "batch": d.get("batch_size"),
            "p50_us": d.get("p50_us"),
            "p99_us": d.get("p99_us"),
            "p999_us": d.get("p999_us"),
            "max_us": d.get("max_us"),
            "mean_us": d.get("mean_us"),
            "std_us": d.get("std_us"),
        })

    # ---- markdown
    headers = ["tag", "arch", "backend", "batch",
               "p50_us", "p99_us", "p999_us", "max_us"]
    print("| " + " | ".join(headers) + " |")
    print("| " + " | ".join(["---"] * len(headers)) + " |")
    for r in rows:
        print("| " + " | ".join(str(r.get(h, "—")) for h in headers) + " |")

    # ---- LaTeX
    tex_path = rdir / "wcet_table.tex"
    lines = [
        "% Generated by experiments/eE_lap_wcet/analyze.py",
        "\\begin{tabular}{lllrrrrr}",
        "\\toprule",
        "Arch & Backend & Device & Batch & P50 ($\\mu$s) & P99 ($\\mu$s) "
        "& P99.9 ($\\mu$s) & Max ($\\mu$s) \\\\",
        "\\midrule",
    ]
    for r in rows:
        cells = [
            r["arch"], r["backend"], r["device"] or "—",
            str(r["batch"]),
            f"{r['p50_us']:.1f}",
            f"{r['p99_us']:.1f}",
            f"{r['p999_us']:.1f}",
            f"{r['max_us']:.1f}",
        ]
        lines.append(" & ".join(cells) + " \\\\")
    lines.extend(["\\bottomrule", "\\end{tabular}"])
    tex_path.write_text("\n".join(lines) + "\n")
    print(f"[eE] wcet_table.tex → {tex_path}")

    if args.no_plot:
        return

    try:
        _plot_wcet_paper(rows, rdir, budget_us=args.budget_us)
    except Exception as e:  # noqa: BLE001
        print(f"[eE] plot skipped: {e}")


def _plot_wcet_paper(rows: list[dict], out_dir: Path, budget_us: float) -> None:
    import matplotlib.pyplot as plt
    import numpy as np

    figstyle.apply()

    # Drop the cross-card probe row from the figure — it muddies the
    # production-vs-baseline contrast that the bar chart is meant to make.
    # The cross-card numbers are already discussed in the §6.7 prose
    # ("Cross-card asymmetry") and live in the table.tex.
    rows = [r for r in rows if r.get("card") != "card1"]

    # Sort: TinyMLP first (TRT, then TRT-fp16, then ONNX, then torch),
    # then BlockRNN/BlockTransformer at the right (worst). Within each
    # backend block, sort by batch ascending.
    BACKEND_ORDER = {"TRT": 0, "TRT-fp16": 1, "ONNX": 2, "torch": 3}
    ARCH_ORDER = {"TinyMLP": 0, "BlockRNN": 1, "BlockTransformer": 2}
    rows = sorted(
        rows,
        key=lambda r: (
            ARCH_ORDER.get(r["arch"], 9),
            BACKEND_ORDER.get(r["backend"], 9),
            r["batch"],
        ),
    )

    # x-tick labels: arch inline only for the single-column Block*
    # groups (BlockRNN / BlockTransformer get one bar each so an overhead
    # header just collides with its neighbour). The big TinyMLP block
    # shows backend / batch on the tick and a "TinyMLP" header on top.
    arch_short = {"BlockRNN": "BlockRNN", "BlockTransformer": "Block-Xfmr"}
    labels = []
    for r in rows:
        if r["arch"] == "TinyMLP":
            labels.append(f"{r['backend']}\nB={r['batch']}")
        else:
            labels.append(f"{arch_short[r['arch']]}\n{r['backend']}\nB={r['batch']}")
    p50 = np.array([r["p50_us"] for r in rows])
    p99 = np.array([r["p99_us"] for r in rows])
    p999 = np.array([r["p999_us"] for r in rows])

    # Wider canvas (full IEEE double-column width = 7 in) keeps the
    # 13 bars readable; rotate ticks 0° because we already used 2-line
    # labels above.
    fig, ax = plt.subplots(figsize=(7.1, 2.7))
    x = np.arange(len(labels))
    w = 0.27

    GRAYS = figstyle.GRAYS
    OURS = figstyle.OURS
    HATCHES = figstyle.HATCHES

    is_trt = [(r["arch"] == "TinyMLP" and r["backend"].startswith("TRT")) for r in rows]

    # Group dividers between arch panels (single thin gray rule)
    arch_changes = [i for i in range(1, len(rows)) if rows[i]["arch"] != rows[i-1]["arch"]]
    for ai in arch_changes:
        ax.axvline(ai - 0.5, color="#cccccc", linestyle="-", linewidth=0.6, zorder=0)
    # Only render an overhead "TinyMLP" header (the single-column Block*
    # groups already carry the arch tag inside the tick label).
    if rows and rows[0]["arch"] == "TinyMLP":
        end = arch_changes[0] if arch_changes else len(rows)
        center = 0.5 * (0 + end - 1)
        ax.text(center, 1.04, "TinyMLP",
                transform=ax.get_xaxis_transform(),
                ha="center", va="bottom", fontsize=8, fontweight="bold")

    # P50 (light) / P99 (mid) / P99.9 (dark); orange variants for the
    # TinyMLP TRT rows (= production deployment we defend in §6.7).
    for pos, vals, hatch, label, color_ours, color_base in [
        (-w, p50,  HATCHES[0], "P50",   "#FCEBDD", GRAYS[1]),
        (0,  p99,  HATCHES[1], "P99",   "#F4B27A", GRAYS[2]),
        (w,  p999, HATCHES[3], "P99.9", OURS,      GRAYS[4]),
    ]:
        for i, v in enumerate(vals):
            ax.bar(
                x[i] + pos, v, width=w,
                color=(color_ours if is_trt[i] else color_base),
                edgecolor="black", linewidth=0.6, hatch=hatch,
                label=label if i == 0 else None,
            )

    ax.axhline(budget_us, color="black", linestyle="--", linewidth=0.9)
    ax.text(len(labels) - 0.4, budget_us * 1.10,
            f"WCET budget = {budget_us:.0f} µs",
            ha="right", va="bottom", fontsize=7.5, color="black")

    # Headline annotation on the TinyMLP TRT B=4096 row (matches abstract).
    headline_idx = next(
        (i for i, r in enumerate(rows)
         if r["arch"] == "TinyMLP" and r["backend"] == "TRT"
         and r["batch"] == 4096 and r.get("card") != "card1"),
        None,
    )
    if headline_idx is not None:
        v = p999[headline_idx]
        ax.annotate(
            f"{v:.1f} µs\nP99.9",
            xy=(x[headline_idx] + w, v), xytext=(8, 22),
            textcoords="offset points",
            ha="left", va="bottom",
            fontsize=7.0, color=OURS, fontweight="bold",
            arrowprops=dict(arrowstyle="-", color=OURS, lw=0.6),
        )

    ax.set_yscale("log")
    ax.set_ylabel("Inference latency (µs)")
    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=0, fontsize=6.8, linespacing=0.95)
    # Add a tiny bit of horizontal pad so the leftmost / rightmost tick
    # labels aren't clipped by the spines.
    ax.set_xlim(-0.55, len(labels) - 0.45)
    ax.set_ylim(top=ax.get_ylim()[1] * 2)
    figstyle.add_box_spines(ax)
    leg = ax.legend(loc="upper left", ncol=3, fontsize=7.0)
    leg.get_frame().set_linewidth(0.6)

    out_path = figstyle.save_paper(fig, "wcet", out_dir)
    print(f"[eE] wcet.pdf → {out_path}")


if __name__ == "__main__":
    main()
