"""J.7 aggregator: compute mean ± stdev across 3 seeds for the
eA scale-up sweep, emit a LaTeX table for the body.

Reads experiments/eA_tail_latency/results_j7_scaleup/*.json,
groups by policy across seeds, and reports per-policy:

    P50_mean ± std,  P99_mean ± std,  P999_mean ± std,  miss_mean

Output:
    results_j7_scaleup/table.tex   (LaTeX booktabs table)
    results_j7_scaleup/summary.json (per-policy aggregated stats)
"""
from __future__ import annotations

import json
import statistics
import sys
from collections import defaultdict
from pathlib import Path


def main(in_dir="experiments/eA_tail_latency/results_j7_scaleup"):
    p = Path(in_dir)
    if not p.exists():
        raise SystemExit(f"[J.7-agg] no such dir: {p}")

    by_policy = defaultdict(list)
    for f in sorted(p.glob("*.json")):
        # Skip auxiliary JSONs (bootstrap CI, etc.) — only the
        # runner outputs have these required fields.
        d = json.load(open(f))
        if "tpot_p50_us" not in d or "policy" not in d:
            continue
        by_policy[d["policy"]].append(d)

    if not by_policy:
        raise SystemExit(f"[J.7-agg] no JSONs found in {p}")

    rows = []
    for pol, runs in by_policy.items():
        vec = lambda k: [r[k] / 1000.0 for r in runs]  # us → ms
        row = {
            "policy": pol,
            "n_seeds": len(runs),
            "n_per_seed": runs[0]["num_requests"],
            "max_new_tokens": runs[0].get("max_new_tokens", "?"),
            "p50_ms_mean": statistics.fmean(vec("tpot_p50_us")),
            "p50_ms_std":  statistics.pstdev(vec("tpot_p50_us")) if len(runs) > 1 else 0.0,
            "p99_ms_mean": statistics.fmean(vec("tpot_p99_us")),
            "p99_ms_std":  statistics.pstdev(vec("tpot_p99_us")) if len(runs) > 1 else 0.0,
            "p999_ms_mean": statistics.fmean(vec("tpot_p999_us")),
            "p999_ms_std":  statistics.pstdev(vec("tpot_p999_us")) if len(runs) > 1 else 0.0,
            "miss_mean":   statistics.fmean(r["miss_ratio"] for r in runs),
            "f1_mean":     statistics.fmean(r["f1_mean"] for r in runs),
        }
        rows.append(row)
    rows.sort(key=lambda r: r["p999_ms_mean"])

    summary_path = p / "summary.json"
    summary_path.write_text(json.dumps(rows, indent=2))
    print(f"[J.7-agg] wrote {summary_path}")

    # ---- LaTeX table ----
    lines = [
        "% Generated by experiments/eA_tail_latency/aggregate_j7.py",
        f"% n_seeds={rows[0]['n_seeds']}, n_prompts/seed={rows[0]['n_per_seed']}, "
        f"max_new_tokens={rows[0]['max_new_tokens']}, B_HBM=0.20.",
        "\\begin{tabular}{lcccc}",
        "\\toprule",
        "Policy & P50 (ms) & P99 (ms) & P999 (ms) & miss \\\\",
        "\\midrule",
    ]
    for r in rows:
        bold = r["policy"] == "seer"
        wrap = (lambda s: "\\textbf{" + s + "}") if bold else (lambda s: s)
        p50 = "{:.2f} $\\pm$ {:.2f}".format(r["p50_ms_mean"], r["p50_ms_std"])
        p99 = "{:.2f} $\\pm$ {:.2f}".format(r["p99_ms_mean"], r["p99_ms_std"])
        p999 = "{:.2f} $\\pm$ {:.2f}".format(r["p999_ms_mean"], r["p999_ms_std"])
        miss = "{:.4f}".format(r["miss_mean"])
        lines.append(
            "{} & {} & {} & {} & {} \\\\".format(
                wrap(r["policy"]), wrap(p50), wrap(p99), wrap(p999), wrap(miss)
            )
        )
    lines += ["\\bottomrule", "\\end{tabular}"]
    table_path = p / "table.tex"
    table_path.write_text("\n".join(lines) + "\n")
    print(f"[J.7-agg] wrote {table_path}")

    print("\n[J.7-agg] === aggregated (3-seed mean ± std) ===")
    print(f"{'policy':10} {'P50(ms)':>16} {'P99(ms)':>16} {'P999(ms)':>16} {'miss':>8}")
    for r in rows:
        print(f"{r['policy']:10} "
              f"{r['p50_ms_mean']:7.2f} ±{r['p50_ms_std']:5.2f}   "
              f"{r['p99_ms_mean']:7.2f} ±{r['p99_ms_std']:5.2f}   "
              f"{r['p999_ms_mean']:7.2f} ±{r['p999_ms_std']:5.2f}   "
              f"{r['miss_mean']:8.4f}")


if __name__ == "__main__":
    main(*sys.argv[1:])
