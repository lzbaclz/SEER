"""Aggregate long-context decode results into a single table + JSON.

P1-5 (M9 fix): pairs P99 / P999 / miss / F1 across (policy, budget,
context_length) cells so the paper can show whether SEER's policy gap
survives long-context decode (≥ 32K prefill, ≥ 1024 decode).
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--in_dir", required=True)
    ap.add_argument("--out_tex", required=True)
    ap.add_argument("--out_json", required=True)
    args = ap.parse_args()

    in_dir = Path(args.in_dir)
    rows = []
    for f in sorted(in_dir.glob("*.json")):
        if f.name in {"summary.json", "table.json"}:
            continue
        try:
            with open(f) as fp:
                data = json.load(fp)
        except Exception:
            continue
        # Filename pattern: {policy}_b{btag}_ctx{N}.json
        stem = f.stem
        parts = stem.split("_")
        if len(parts) < 3:
            continue
        policy = parts[0]
        btag = next((p for p in parts if p.startswith("b") and p[1:].isdigit()), "")
        ctx_part = next((p for p in parts if p.startswith("ctx")), "")
        try:
            budget = float("0." + btag[1:]) if btag else float("nan")
        except ValueError:
            budget = float("nan")
        try:
            ctx = int(ctx_part[3:]) if ctx_part else int(data.get("context_length", 0))
        except ValueError:
            ctx = int(data.get("context_length", 0))
        rows.append({
            "policy": policy,
            "budget": budget,
            "ctx": ctx,
            "p50_ms": data.get("tpot_p50_us", 0) / 1000.0,
            "p99_ms": data.get("tpot_p99_us", 0) / 1000.0,
            "p999_ms": data.get("tpot_p999_us", 0) / 1000.0,
            "miss_ratio": data.get("miss_ratio", 0),
            "f1": data.get("f1_mean", 0),
            "max_new_tokens": data.get("results", [{}])[0].get("n_gen_tokens", 0),
        })

    rows.sort(key=lambda r: (r["ctx"], r["budget"], r["policy"]))

    # Write JSON summary.
    out_json = Path(args.out_json)
    out_json.parent.mkdir(parents=True, exist_ok=True)
    with open(out_json, "w") as fp:
        json.dump({"rows": rows, "n_cells": len(rows)}, fp, indent=2)

    # Write LaTeX table.
    out_tex = Path(args.out_tex)
    with open(out_tex, "w") as fp:
        fp.write("% Generated by experiments/eA_tail_latency/aggregate_longctx.py\n")
        fp.write("\\begin{tabular}{lrrrrrr}\n\\toprule\n")
        fp.write("Policy & $\\phi$ & ctx & P99 (ms) & P999 (ms) & Miss & F1 \\\\\n")
        fp.write("\\midrule\n")
        for r in rows:
            fp.write(
                f"{r['policy']} & {r['budget']:.2f} & "
                f"{r['ctx']:,} & {r['p99_ms']:.1f} & {r['p999_ms']:.1f} & "
                f"{r['miss_ratio']:.4f} & {r['f1']:.3f} \\\\\n"
            )
        fp.write("\\bottomrule\n\\end{tabular}\n")
    print(f"wrote {out_tex} ({len(rows)} rows) and {out_json}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
