"""Compare raw-trace replay unsafe tallies: lognormal vs recorded IO (R30).

Runs ``raw_trace_replay`` logic twice at $B_t=32$ for the three
headline variants cited in §VI.F and emits
``raw_trace_io_mode_compare.{json,tex}`` for supplementary disclosure.
"""
from __future__ import annotations

import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
RESULTS = ROOT / "experiments/eC_bound_tightness/results"
HEADLINE_VARIANTS = (
    "bernstein-cor2",
    "full-tail-guard",
    "full-tail-PS",
)


def _run_mode(io_mode: str, out_suffix: str) -> None:
    cmd = [
        sys.executable,
        "-m",
        "experiments.eC_bound_tightness.raw_trace_replay",
        "--io_mode",
        io_mode,
        "--out_suffix",
        out_suffix,
    ]
    subprocess.run(cmd, cwd=str(ROOT), check=True)


def _load_tallies(path: pathlib.Path) -> dict[str, dict]:
    data = json.loads(path.read_text())
    out = {}
    for variant in HEADLINE_VARIANTS:
        t = data["regimes"][variant]["tally"]
        out[variant] = {
            "accepted": int(t["accepted"]),
            "unsafe": int(t["unsafe_accepts"]),
            "black": int(t["black"]),
        }
    return out


def _write_tex(logn: dict, rec: dict) -> str:
    lines = [
        "% Generated by raw_trace_io_mode_compare.py (R30).",
        r"\begin{tabular}{lrrrr}",
        r"\toprule",
        r"Variant & \multicolumn{2}{c}{accepted / 36} & "
        r"\multicolumn{2}{c}{unsafe accepts} \\",
        r" & LogNormal & recorded & LogNormal & recorded \\",
        r"\midrule",
    ]
    for v in HEADLINE_VARIANTS:
        lg, rc = logn[v], rec[v]
        lines.append(
            f"\\texttt{{{v}}} & ${lg['accepted']}$ & ${rc['accepted']}$ & "
            f"${lg['unsafe']}$ & ${rc['unsafe']}$ \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def main() -> int:
    print("[io-mode-compare] running lognormal replay ...")
    _run_mode("lognormal", "")
    print("[io-mode-compare] running recorded replay ...")
    _run_mode("recorded", "_recorded")

    logn = _load_tallies(RESULTS / "raw_trace_replay.json")
    rec = _load_tallies(RESULTS / "raw_trace_replay_recorded.json")

    identical = all(
        logn[v]["unsafe"] == rec[v]["unsafe"]
        and logn[v]["accepted"] == rec[v]["accepted"]
        for v in HEADLINE_VARIANTS
    )
    summary = {
        "B_t": 32,
        "headline_variants": list(HEADLINE_VARIANTS),
        "lognormal": logn,
        "recorded": rec,
        "unsafe_tally_identical": identical,
        "interpretation": (
            "Headline unsafe/accept counts are identical under "
            "LogNormal parametric IO vs trace-recorded per_step_io_us "
            if identical
            else "Unsafe/accept counts differ between LogNormal and "
                 "recorded IO on at least one headline variant."
        ),
    }
    out_json = RESULTS / "raw_trace_io_mode_compare.json"
    out_json.write_text(json.dumps(summary, indent=2))
    out_tex = RESULTS / "raw_trace_io_mode_compare.tex"
    out_tex.write_text(_write_tex(logn, rec))
    print(f"[io-mode-compare] identical={identical}")
    for v in HEADLINE_VARIANTS:
        print(f"  {v:20s} lognormal {logn[v]['accepted']}/{logn[v]['unsafe']}  "
              f"recorded {rec[v]['accepted']}/{rec[v]['unsafe']}")
    print(f"[io-mode-compare] wrote {out_json} and {out_tex}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
