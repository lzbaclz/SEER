"""R9 interference-aware bound (replaces R7 A6 no-interference).

The R7 paper added an explicit `A6 (no-interference)` assumption to
Theorem 1, acknowledging that the test treats streams as
independent under Poisson arrival. The R8 self-review correctly
identifies this as the largest theoretical hand-wave: hard-RT
reviewers will require at least a *blocking* term capturing how
many slots a stream can wait at the shared substrate before its
own decode step starts.

This script:

1. Computes an empirical blocking term `B_i` from the existing
   `sigma_contention_regimes.json` (worst-case contention bound:
   the cross_card regime's max sigma_ratio = 2.65 x quiet).
2. Re-runs the admission test on 1/2/4/8 co-scheduled streams,
   inflating sigma_residual_us by `(1 + (n_streams - 1) * B_i /
   B_full)` to model shared-substrate queue blocking.
3. Reports actionable-cell count + UNSAFE false-accept count at
   each n_streams. This is the bound's robustness under interference.

Outputs: interference_aware.{json,tex}.
"""
from __future__ import annotations

import json
import pathlib
import sys

from experiments.eC_bound_tightness.admission_map import (
    SUBSTRATES, D_GRID_MS, PHI_GRID, RHO_TARGET,
    load_dense_eps, interp_eps, bound_verdict, empirical_miss,
    classify, _stable_seed,
)


ROOT = pathlib.Path(__file__).resolve().parents[2]
RESULTS = ROOT / "experiments/eC_bound_tightness/results"


def load_blocking_term() -> dict:
    """Load worst-case contention bound from the existing eFault
    sigma_contention_regimes.json. The bound's B_i input is the
    worst-trial sigma_ratio over the 4 measured contention regimes
    (quiet, cross_card, memalloc, pcie), 3 trials each."""
    p = ROOT / "experiments/eFault_characterization/results/sigma_contention_regimes.json"
    d = json.loads(p.read_text())
    worst_ratio = 1.0
    worst_regime = "quiet"
    per_regime = {}
    for r in d["rows"]:
        m = float(r["sigma_ratio_max"])
        per_regime[r["regime"]] = {
            "mean_ratio": float(r["sigma_ratio_vs_quiet"]),
            "max_ratio": m,
        }
        if m > worst_ratio:
            worst_ratio = m
            worst_regime = r["regime"]
    return {
        "worst_regime": worst_regime,
        "worst_sigma_ratio": worst_ratio,
        "per_regime": per_regime,
    }


def main() -> int:
    blocking = load_blocking_term()
    B_i = blocking["worst_sigma_ratio"]
    print(f"[interference] worst-case blocking term B_i = {B_i:.3f}x "
          f"(regime: {blocking['worst_regime']})")

    curve = load_dense_eps(RESULTS / "dense_deployed_eps_summary.json")

    base_cost_us = 33800.0
    sigma_quiet_us = 1203.0
    rho_bar = 0.08

    n_streams_grid = [1, 2, 4, 8]
    rows = []
    for n_streams in n_streams_grid:
        # Interference inflation: shared substrate adds (n_streams - 1)
        # * (B_i - 1) * sigma_quiet to sigma_residual.
        sigma_eff = sigma_quiet_us * (1.0 + max(0.0, n_streams - 1) * (B_i - 1.0))
        tally = {"green": 0, "red": 0, "yellow": 0, "black": 0}
        actionable = 0
        for substrate, (ell_bar, _) in SUBSTRATES.items():
            for D_ms in D_GRID_MS:
                D_us = D_ms * 1000.0
                for phi in PHI_GRID:
                    eps_mean, _ = interp_eps(phi, curve)
                    ba = bound_verdict(
                        eps_mean, ell_bar, D_us, RHO_TARGET,
                        rho_bar, base_cost_us, sigma_eff,
                        include_io_cost=True,
                        use_heavy_tail=False)
                    # Empirical truth: also inflated by interference.
                    em = empirical_miss(
                        eps_mean, 0.0, ell_bar, D_us,
                        rho_bar=0.08,
                        base_cost_us=base_cost_us,
                        sigma_residual_us=sigma_eff,
                        seed=_stable_seed(substrate, D_ms, phi, n_streams))
                    cell = classify(ba, em, RHO_TARGET)
                    tally[cell] += 1
                    if ba:
                        actionable += 1
        rows.append({
            "n_streams": n_streams,
            "sigma_eff_us": sigma_eff,
            "actionable": actionable,
            "tally": tally,
        })
        print(f"[interference] n_streams={n_streams}: sigma_eff={sigma_eff:.1f}us, "
              f"actionable={actionable}, tally={tally}")

    out = {
        "blocking": blocking,
        "B_i": B_i,
        "rows": rows,
    }
    (RESULTS / "interference_aware.json").write_text(json.dumps(out, indent=2))
    print(f"[interference] wrote {RESULTS / 'interference_aware.json'}")

    # TeX table for §6.
    lines = [
        "% Generated by interference_aware_bound.py (R9 RTSS strong-accept).",
        "% Multi-stream admission under measured-bounded interference",
        f"% (worst-case B_i = {B_i:.2f}x quiet sigma, regime: "
        f"{blocking['worst_regime']}).",
        r"\begin{tabular}{rrrrrrr}",
        r"\toprule",
        r"$n_\text{streams}$ & $\sigma_\text{eff}$ (us) & green & "
        r"red & yellow & black & accept rate \\",
        r"\midrule",
    ]
    for r in rows:
        n_total = sum(r["tally"].values())
        accept = (r["tally"]["green"] + r["tally"]["black"]) / max(n_total, 1)
        unsafe = "\\textbf{" + str(r["tally"]["black"]) + "}" if r["tally"]["black"] > 0 else str(r["tally"]["black"])
        lines.append(
            f"${r['n_streams']}$ & ${r['sigma_eff_us']:.0f}$ & "
            f"${r['tally']['green']}$ & ${r['tally']['red']}$ & "
            f"${r['tally']['yellow']}$ & ${unsafe}$ & "
            f"${100 * accept:.1f}\\%$ \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    (RESULTS / "interference_aware.tex").write_text("\n".join(lines) + "\n")
    print(f"[interference] wrote {RESULTS / 'interference_aware.tex'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
