"""Sizing rule under deployed-epsilon (R3-W4 follow-through).

The headline `tab:eC-sizing-io-bound` is generated by inverting Lemma~2
against the *calibrated* bi-normal $\\epsilon(\\phi)$ curve. The
dense-deployed-eps experiment (`dense_deployed_eps.py`) shows that the
deployed $\\epsilon(\\phi)$ at the same $\\phi$ knots is
$2.06$--$2.93\\times$ higher than the calibrated curve.

This script re-runs the IO-bound sizing inversion under the *deployed*
$\\epsilon(\\phi)$ via `min_hbm_budget_for_slo_measured`. The output is
the "deployment-grade" column of the sizing table: how many cells does
the bound actually return an operator-actionable $\\phi^{\\min}$ once
the optimism of the calibrated curve is removed?

Outputs:
- ``sizing_rule_deployed_eps.tex`` — TeX table replacing the
  ``sizing_rule_io_bound.tex`` headline cells with deployed-$\\epsilon$
  inputs.
- ``sizing_rule_deployed_eps_summary.json``
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from seer.timing.schedulability import min_hbm_budget_for_slo_measured


# Substrate definitions (match io_bound_regime.py).
SUBSTRATES = [
    ("DRAM",    200.0,  1500.0),
    ("NVMe",    1500.0, 3000.0),
    ("NVMe-GC", 2000.0, 5000.0),
]
# Cells from the headline `sizing_rule_io_bound.tex`.
CELLS = [
    ("DRAM",    35,  1e-2),
    ("DRAM",    35,  1e-3),
    ("DRAM",    50,  1e-2),
    ("DRAM",    50,  1e-3),
    ("DRAM",    75,  1e-2),
    ("DRAM",    75,  1e-3),
    ("DRAM",    100, 1e-2),
    ("DRAM",    100, 1e-3),
    ("NVMe",    35,  1e-2),
    ("NVMe",    50,  1e-2),
    ("NVMe",    75,  1e-2),
    ("NVMe",    75,  1e-3),
    ("NVMe",    100, 1e-2),
    ("NVMe",    100, 1e-3),
    ("NVMe-GC", 35,  1e-2),
    ("NVMe-GC", 50,  1e-2),
    ("NVMe-GC", 75,  1e-2),
    ("NVMe-GC", 75,  1e-3),
    ("NVMe-GC", 100, 1e-2),
    ("NVMe-GC", 100, 1e-3),
]


def _load_dense_eps(path: Path) -> list[tuple[float, float]]:
    """Load dense_deployed_eps_summary.json and return the deployed
    eps curve as [(phi, eps), ...]."""
    with open(path) as fh:
        data = json.load(fh)
    return [(r["phi"], r["deployed_mean"]) for r in data["rows"]]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dense_eps",
                    default="experiments/eC_bound_tightness/results/dense_deployed_eps_summary.json")
    ap.add_argument("--B_full", type=float, default=512.0)
    ap.add_argument("--sigma_residual_us", type=float, default=1203.0)
    ap.add_argument("--base_cost_us", type=float, default=33800.0,
                    help="mu_0 (median IO-free TPOT) in us")
    ap.add_argument("--out_dir",
                    default="experiments/eC_bound_tightness/results")
    args = ap.parse_args()

    dense_eps_path = Path(args.dense_eps)
    deployed_curve = _load_dense_eps(dense_eps_path)
    # Calibrated bi-normal anchors (matches dense_deployed_eps.py).
    calibrated_curve = [(0.10, 0.40), (0.20, 0.32), (0.40, 0.22),
                         (0.80, 0.054)]

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    POLICY_FLOOR = 0.125

    rows: list[dict] = []
    actionable_calib = 0
    actionable_depl = 0
    for substrate, D_ms, rho in CELLS:
        ell_bar_us = next(e for s, e, _ in SUBSTRATES if s == substrate)
        D_us = D_ms * 1000.0
        try:
            phi_calib = min_hbm_budget_for_slo_measured(
                eps_curve=calibrated_curve,
                ell_bar_us=ell_bar_us,
                B_full=args.B_full,
                deadline_us=D_us,
                sigma_residual_us=args.sigma_residual_us,
                miss_target=rho,
                base_cost_us=args.base_cost_us,
            )
        except Exception:
            phi_calib = 1.0
        try:
            phi_depl = min_hbm_budget_for_slo_measured(
                eps_curve=deployed_curve,
                ell_bar_us=ell_bar_us,
                B_full=args.B_full,
                deadline_us=D_us,
                sigma_residual_us=args.sigma_residual_us,
                miss_target=rho,
                base_cost_us=args.base_cost_us,
            )
        except Exception:
            phi_depl = 1.0
        rows.append({
            "substrate": substrate,
            "D_ms": D_ms,
            "rho": rho,
            "phi_calib": phi_calib,
            "phi_depl": phi_depl,
            "calib_strictly_above_floor": phi_calib > POLICY_FLOOR + 1e-9,
            "depl_strictly_above_floor": phi_depl > POLICY_FLOOR + 1e-9,
            "depl_operator_actionable": (
                POLICY_FLOOR < phi_depl <= 1.0 - 1e-3),
            "calib_operator_actionable": (
                POLICY_FLOOR < phi_calib <= 1.0 - 1e-3),
        })
        if rows[-1]["calib_operator_actionable"]:
            actionable_calib += 1
        if rows[-1]["depl_operator_actionable"]:
            actionable_depl += 1
        print(f"[sizing-deployed] {substrate:8s} D={D_ms:3d}ms rho={rho:.0e}: "
              f"calib_phi={phi_calib:.3f}  deployed_phi={phi_depl:.3f}")

    print(f"[sizing-deployed] operator-actionable cells: "
          f"calibrated {actionable_calib}/{len(CELLS)}  "
          f"deployed {actionable_depl}/{len(CELLS)}")

    summary = {
        "policy_floor": POLICY_FLOOR,
        "calib_curve": calibrated_curve,
        "deployed_curve": deployed_curve,
        "n_cells_total": len(CELLS),
        "n_actionable_calib": actionable_calib,
        "n_actionable_depl": actionable_depl,
        "rows": rows,
    }
    out_json = out_dir / "sizing_rule_deployed_eps_summary.json"
    with open(out_json, "w") as fh:
        json.dump(summary, fh, indent=2)
    print(f"[sizing-deployed] wrote {out_json}")

    # TeX table.
    lines = [
        "% Generated by experiments/eC_bound_tightness/sizing_deployed_eps.py",
        "% R3-W4 follow-through: sizing rule recomputed with deployed eps.",
        "% Cells with phi_depl <= floor or phi_depl > 1 are reported as",
        "% 'floor' or 'infeasible'. Operator should consume the deployed",
        "% column at deployment; the calibrated column is for budgeting.",
        r"\begin{tabular}{lrrrr}",
        r"\toprule",
        r"Substrate & $D$ & $\rho$ & "
        r"$\hbm^{\mathrm{min},\mathrm{calib}}$ & "
        r"$\hbm^{\mathrm{min},\mathrm{depl}}$ \\",
        r"\midrule",
    ]
    for r in rows:
        def _cell(phi: float) -> str:
            if phi <= POLICY_FLOOR + 1e-9:
                return r"$\to\text{floor}$"
            if phi >= 1.0 - 1e-3:
                return r"$\text{infeas.}$"
            return f"${phi:.3f}$"
        lines.append(
            f"{r['substrate']} & "
            f"${r['D_ms']}$\\,ms & "
            f"${r['rho']:.0e}$ & "
            f"{_cell(r['phi_calib'])} & "
            f"{_cell(r['phi_depl'])} \\\\"
        )
    lines.extend([
        r"\midrule",
        f"\\multicolumn{{5}}{{l}}{{\\textit{{Operator-actionable cells: "
        f"calibrated ${actionable_calib}/{len(CELLS)}$ "
        f"({100 * actionable_calib // len(CELLS)}\\%); "
        f"deployed ${actionable_depl}/{len(CELLS)}$ "
        f"({100 * actionable_depl // len(CELLS)}\\%).}}}} \\\\",
        r"\bottomrule",
        r"\end{tabular}",
    ])
    out_tex = out_dir / "sizing_rule_deployed_eps.tex"
    with open(out_tex, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"[sizing-deployed] wrote {out_tex}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
