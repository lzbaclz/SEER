"""eF analyze — mixed-SLO miss ratio matrix.

Aggregates per-policy JSONs from the driver into a comparison matrix
of (chat_miss_ratio, doc_miss_ratio) per policy and emits both a
markdown table and a Patrick / ADSLab style grouped bar figure.

Also writes:
* ``miss_table.tex`` — paper-ready LaTeX two-column table consumed by
  §6.8 (replaces the "varies / --" placeholder cells).
* ``summary.json`` — chat / doc miss-ratio per policy.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

_REPO = Path(__file__).resolve().parents[2]
if str(_REPO) not in sys.path:
    sys.path.insert(0, str(_REPO))

from seer import figstyle  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("results_dir")
    ap.add_argument("--no_plot", action="store_true")
    ap.add_argument("--floor", type=float, default=1e-3,
                    help="Floor used when plotting log-y miss ratios "
                         "(default 1e-3).")
    args = ap.parse_args()

    rdir = Path(args.results_dir)
    files = sorted(rdir.glob("*.json"))
    files = [f for f in files if f.stem != "summary"]
    if not files:
        raise SystemExit(f"no JSON under {rdir}")

    rows = []
    for f in files:
        with open(f) as fh:
            d = json.load(fh)
        # Driver writes either chat_miss_ratio (simulator backend) or
        # chat_miss (vllm backend). Same metric, different field name.
        chat_miss = d.get("chat_miss_ratio", d.get("chat_miss", 0.0))
        doc_miss = d.get("doc_miss_ratio", d.get("doc_miss", 0.0))
        rows.append({
            "tag": f.stem,
            "policy": d.get("policy"),
            "backend": d.get("backend", "simulator"),
            "chat_miss": float(chat_miss),
            "doc_miss":  float(doc_miss),
            "n_chat": d.get("n_chat"),
            "n_doc":  d.get("n_doc"),
            "wall_time_s": float(d.get("wall_time_s", 0.0)),
        })

    # Sort by (chat:doc ratio, policy) so multi-ratio runs render with
    # each (n_chat, n_doc) block of policies adjacent in the table.
    rows.sort(
        key=lambda r: (
            (r.get("n_chat") or 0, r.get("n_doc") or 0),
            figstyle.policy_sort_key(r["policy"]),
        )
    )

    # ---- markdown
    print("| policy | chat miss | doc miss | wall (s) |")
    print("| --- | --- | --- | --- |")
    for r in rows:
        print(f"| {r['policy']} | {r['chat_miss']:.4f} | "
              f"{r['doc_miss']:.4f} | {r['wall_time_s']:.1f} |")

    # ---- summary.json (helps the §6.8 table consumer)
    summary_path = rdir / "summary.json"
    with open(summary_path, "w") as fh:
        json.dump(
            {r["policy"]: {"chat_miss": r["chat_miss"],
                           "doc_miss": r["doc_miss"],
                           "wall_time_s": r["wall_time_s"]}
             for r in rows},
            fh, indent=2,
        )
    print(f"[eF] summary.json → {summary_path}")

    # ---- LaTeX (paper-ready)
    tex_path = rdir / "miss_table.tex"
    _write_latex_table(tex_path, rows)
    print(f"[eF] miss_table.tex → {tex_path}")

    if args.no_plot:
        return
    try:
        _plot_miss_matrix_paper(rows, rdir, floor=args.floor)
    except Exception as e:  # noqa: BLE001
        print(f"[eF] plot skipped: {e}")


def _write_latex_table(path: Path, rows: list[dict]) -> None:
    # Two-column percentage table; header matches the §6.8 placeholder so
    # the §6 .tex can be rewritten with \input{...}. If the results
    # directory contains multiple (n_chat, n_doc) ratios (i.e. eF was
    # re-run with `make eF-multimix`), each policy gets one row per
    # ratio with the ratio prefix in the policy column.
    ratios = sorted({(r.get("n_chat"), r.get("n_doc")) for r in rows})
    multi_ratio = len(ratios) > 1

    lines = [
        "% Generated by experiments/eF_mixed_slo/analyze.py",
        "\\begin{tabular}{lrr}",
        "\\toprule",
        ("Policy (chat:doc) & chat\\_miss & doc\\_miss \\\\"
         if multi_ratio
         else "Policy & chat\\_miss & doc\\_miss \\\\"),
        "\\midrule",
    ]
    for r in rows:
        pol = (r["policy"] or "?").lower()
        bf = "\\textbf{" if pol == "seer" else ""
        bf_end = "}" if pol == "seer" else ""
        label = figstyle.policy_label(pol)
        if multi_ratio:
            label = f"{label} ({r.get('n_chat')}:{r.get('n_doc')})"
        lines.append(
            f"{bf}{label}{bf_end} & "
            f"{bf}{r['chat_miss']*100:.2f}\\%{bf_end} & "
            f"{bf}{r['doc_miss']*100:.2f}\\%{bf_end} \\\\"
        )
    lines.extend(["\\bottomrule", "\\end{tabular}"])
    path.write_text("\n".join(lines) + "\n")


def _short_policy_label(policy: str) -> str:
    short = {
        "Full (no eviction)": "Full",
        "StreamingLLM":       "Stream",
        "Recency":            "Rec.",
        "SnapKV":             "Snap",
        "Quest":              "Quest",
        "H2O":                "H2O",
        "SEER":               "SEER",
    }
    return short.get(figstyle.policy_label(policy), figstyle.policy_label(policy))


def _annotate_miss_pct(ax, x: float, y: float, value: float, *,
                       is_ours: bool = False) -> None:
    """Label only non-degenerate miss ratios (skip 0% and 100%)."""
    if value >= 0.995 or value < 0.005:
        return
    figstyle.annotate_topbar(
        ax, x, y, f"{value * 100:.1f}%",
        is_ours=is_ours, dy_pt=1.5,
    )


def _plot_miss_matrix_paper(rows: list[dict], out_dir: Path,
                            floor: float) -> None:
    import matplotlib.patches as mpatches
    import matplotlib.pyplot as plt
    from collections import defaultdict

    figstyle.apply()

    groups: dict[tuple[int | None, int | None], list[dict]] = defaultdict(list)
    for r in rows:
        groups[(r.get("n_chat"), r.get("n_doc"))].append(r)
    group_keys = sorted(groups)
    for key in group_keys:
        groups[key].sort(key=lambda r: figstyle.policy_sort_key(r["policy"]))

    multi_ratio = len(group_keys) > 1
    bar_w = 0.11
    pair_gap = 0.04
    policy_step = 2 * bar_w + pair_gap + 0.06
    group_gap = 0.45

    placements: list[tuple[float, dict]] = []
    group_centers: list[float] = []
    x_cursor = 0.0
    for gkey in group_keys:
        grows = groups[gkey]
        group_start = x_cursor
        for pidx, r in enumerate(grows):
            cx = group_start + pidx * policy_step + policy_step / 2
            placements.append((cx, r))
        group_centers.append(
            group_start + (len(grows) - 1) * policy_step / 2 + policy_step / 2
        )
        x_cursor = group_start + len(grows) * policy_step + group_gap

    max_policies = max(len(groups[k]) for k in group_keys)
    fig_w = 3.45 if max_policies <= 3 else 5.2
    fig, ax = plt.subplots(figsize=(fig_w, 2.55))
    fig.subplots_adjust(bottom=0.34 if multi_ratio else 0.24)

    for cx, r in placements:
        is_ours = (r["policy"] or "").lower() == "seer"
        chat_y = max(r["chat_miss"], floor)
        doc_y = max(r["doc_miss"], floor)
        ax.bar(
            cx - bar_w / 2 - pair_gap / 2, chat_y, bar_w,
            color=(figstyle.OURS if is_ours else figstyle.GRAYS[2]),
            edgecolor="black", linewidth=0.6, hatch="//",
        )
        ax.bar(
            cx + bar_w / 2 + pair_gap / 2, doc_y, bar_w,
            color="white",
            edgecolor="black", linewidth=0.6, hatch="xx",
        )
        _annotate_miss_pct(
            ax, cx - bar_w / 2 - pair_gap / 2, chat_y,
            r["chat_miss"], is_ours=is_ours,
        )
        _annotate_miss_pct(
            ax, cx + bar_w / 2 + pair_gap / 2, doc_y,
            r["doc_miss"], is_ours=False,
        )

    ax.axhline(0.01, color="black", linestyle=":", linewidth=0.7, zorder=0)
    ax.text(
        ax.get_xlim()[1], 0.012, "1% target",
        ha="right", va="bottom", fontsize=6.5, color="black",
    )

    ax.set_yscale("log")
    ax.set_ylim(floor * 0.5, 1.6)
    ax.set_xlim(-0.25, x_cursor - group_gap + 0.25)
    ax.set_xticks([cx for cx, _ in placements])
    ax.set_xticklabels(
        [_short_policy_label(r["policy"]) for _, r in placements],
        fontsize=7,
    )
    ax.set_ylabel("Miss ratio")

    if multi_ratio:
        for gc, (nc, nd) in zip(group_centers, group_keys):
            ax.text(
                gc, -0.34, f"chat:doc = {nc}:{nd}",
                transform=ax.get_xaxis_transform(),
                ha="center", va="top", fontsize=6.8, fontweight="bold",
            )
        ax.tick_params(axis="x", pad=4)

    legend_proxies = [
        mpatches.Patch(facecolor=figstyle.GRAYS[2], edgecolor="black",
                       linewidth=0.6, hatch="//", label="chat (TPOT P99)"),
        mpatches.Patch(facecolor="white", edgecolor="black",
                       linewidth=0.6, hatch="xx", label="doc (TTFT P99)"),
        mpatches.Patch(facecolor=figstyle.OURS, edgecolor="black",
                       linewidth=0.6, hatch="//", label="SEER chat"),
    ]
    fig.legend(
        handles=legend_proxies,
        loc="upper center",
        bbox_to_anchor=(0.5, 0.04),
        ncol=3,
        fontsize=6.5,
        frameon=False,
        handlelength=1.2,
        columnspacing=0.9,
    )
    figstyle.add_box_spines(ax)

    out_path = figstyle.save_paper(fig, "miss_matrix", out_dir)
    print(f"[eF] miss_matrix.pdf → {out_path}")


if __name__ == "__main__":
    main()
