"""Per-seed step-miss table from stored chat_miss_step_level (not interp).

Addresses reviewer W3: 'report per-seed table, expose H2O outlier and
SEER vs Streaming tie'.

Two-sample Wilson z-tests:
- SEER vs H2O
- SEER vs Streaming
- SEER vs full
across the pooled (k, n) per policy.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path


def two_sample_z(k_a: int, n_a: int, k_b: int, n_b: int) -> tuple[float, float]:
    if n_a == 0 or n_b == 0:
        return 0.0, 1.0
    p_a, p_b = k_a / n_a, k_b / n_b
    p_pool = (k_a + k_b) / (n_a + n_b)
    se = math.sqrt(p_pool * (1 - p_pool) * (1 / n_a + 1 / n_b))
    if se == 0:
        return 0.0, 1.0
    z = (p_a - p_b) / se
    p_val = math.erfc(abs(z) / math.sqrt(2))
    return z, p_val


def diff_ci(k_a: int, n_a: int, k_b: int, n_b: int,
            z: float = 1.96) -> tuple[float, float]:
    """Wald 95% CI on the difference p_a - p_b."""
    if n_a == 0 or n_b == 0:
        return float("nan"), float("nan")
    p_a, p_b = k_a / n_a, k_b / n_b
    se = math.sqrt(p_a * (1 - p_a) / n_a + p_b * (1 - p_b) / n_b)
    return p_a - p_b - z * se, p_a - p_b + z * se


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--in_dir",
                    default="experiments/eF_mixed_slo/results_vllm_path_beta3")
    ap.add_argument("--out", default=None)
    args = ap.parse_args()
    in_dir = Path(args.in_dir)
    out_path = (Path(args.out) if args.out
                else in_dir / "multiturn_per_seed_stored.tex")

    by_policy: dict[str, dict[int, dict]] = {}
    for f in sorted(in_dir.glob("*_s*.json")):
        if ".contention." in f.name or "summary" in f.name or "aggregate" in f.name:
            continue
        policy = f.name.split("_")[0]
        try:
            seed = int(f.stem.split("_s")[1])
        except Exception:
            continue
        try:
            with open(f) as fh:
                d = json.load(fh)
        except Exception:
            continue
        total_n = 0
        total_miss = 0
        for r in d.get("results", []):
            ts = r.get("tpot_stats") or r.get("stats") or {}
            total_n += int(ts.get("n", 0))
            total_miss += int(ts.get("miss_count", ts.get("misses", 0)))
        by_policy.setdefault(policy, {})[seed] = {
            "miss_rate": (total_miss / total_n) if total_n else 0.0,
            "k": total_miss,
            "n": total_n,
        }
    seeds = sorted({s for v in by_policy.values() for s in v.keys()})
    lines = [
        "% Generated by per_seed_table.py.",
        "% Per-seed step-miss at the actual SLO of the run "
        "(P99=200ms), from stored chat_miss_step_level.",
        r"\begin{tabular}{l" + "r" * (len(seeds) + 2) + "}",
        r"\toprule",
        "Policy & " + " & ".join(f"s{s}" for s in seeds)
        + r" & pooled $\hat{p}$ & 95\% Wilson CI \\",
        r"\midrule",
    ]
    pol_pooled: dict[str, tuple[int, int]] = {}
    for policy in ("full", "streaming", "h2o", "snapkv", "quest", "seer"):
        if policy not in by_policy:
            continue
        seed_map = by_policy[policy]
        cells = []
        pooled_k = 0
        pooled_n = 0
        for s in seeds:
            d = seed_map.get(s)
            if d is None:
                cells.append("--")
            else:
                cells.append(rf"${d['miss_rate']:.4f}$")
                pooled_k += d["k"]
                pooled_n += d["n"]
        pol_pooled[policy] = (pooled_k, pooled_n)
        if pooled_n > 0:
            p_hat = pooled_k / pooled_n
            # Wilson CI
            z = 1.96
            den = 1.0 + z * z / pooled_n
            centre = (p_hat + z * z / (2 * pooled_n)) / den
            half = z * math.sqrt(p_hat * (1 - p_hat) / pooled_n
                                 + z * z / (4 * pooled_n * pooled_n)) / den
            lo, hi = max(0, centre - half), min(1, centre + half)
            cells.extend([rf"${p_hat:.4f}$", rf"$[{lo:.4f}, {hi:.4f}]$"])
        else:
            cells.extend(["--", "--"])
        lines.append(rf"\texttt{{{policy}}} & " + " & ".join(cells) + r" \\")
    # Two-sample tests
    lines.extend([
        r"\midrule",
        r"\multicolumn{" + str(len(seeds) + 3)
        + r"}{l}{\textit{Two-sample $z$-tests against \texttt{seer}}"
        r" (\emph{negative} $z$ means \texttt{seer} better):} \\",
    ])
    if "seer" in pol_pooled:
        k_s, n_s = pol_pooled["seer"]
        for other in ("h2o", "streaming", "full"):
            if other not in pol_pooled:
                continue
            k_o, n_o = pol_pooled[other]
            z, p = two_sample_z(k_s, n_s, k_o, n_o)
            d_lo, d_hi = diff_ci(k_s, n_s, k_o, n_o)
            sig_inner = (r"{<}10^{-3}" if p < 0.001
                         else f"{{=}}{p:.3f}")
            lines.append(
                rf"\hspace{{1em}}\texttt{{seer}} vs.\ \texttt{{{other}}} "
                + "& " + " & ".join(["--"] * len(seeds))
                + rf" & $z{{=}}{{{'+' if z >= 0 else '-'}}}{abs(z):.2f}$, $p{sig_inner}$, $\Delta\hat{{p}}\in["
                + (f"{d_lo:+.4f}, {d_hi:+.4f}" if not math.isnan(d_lo) else "n/a")
                + r"]$ & \\")
    lines.extend([r"\bottomrule", r"\end{tabular}"])
    out_path.write_text("\n".join(lines) + "\n")
    print(f"wrote {out_path}")
    # Also print to stdout for the paper-writing pass.
    print("\nPer-seed table preview:")
    for line in lines[3:-2]:
        print("  " + line.replace(r"\texttt{", "").replace("}", "").replace(
            "$", "").replace(r"\\", ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
