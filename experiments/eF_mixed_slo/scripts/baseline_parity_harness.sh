#!/usr/bin/env bash
# R17 public-reference baseline parity harness (RTSS reviewer #3).
#
# Re-runs the §VI.F vLLM 6-way SLO sweep using *upstream reference*
# H2O / SnapKV / Quest implementations rather than the in-tree
# policy-only re-implementations in seer.policy.baselines. The
# RTSS reviewer correctly notes that policy-only re-implementations
# are not faithful end-to-end ports, and the head-to-head numbers
# need cross-validation against the upstream artefacts.
#
# This script pins the upstream commit hashes that produced the
# published numbers for each baseline. It is GPU-required (1x A100
# minimum, 4x preferred for the 6-way sweep at scale) and is the
# load-bearing follow-up for RTSS reviewer #3 / ATC reviewer #5.
#
# Without GPUs the script reports the pinned commit set and exits
# cleanly so the artifact tree documents what would run.
set -euo pipefail

OUT_DIR="${OUT_DIR:-experiments/eF_mixed_slo/results_vllm_baseline_parity}"
mkdir -p "$OUT_DIR"

# ---------------------------------------------------------------
# Pinned public-reference commits (R17). All commits are from the
# author repositories used in the original publications. Update via
# `git submodule` if the upstream repositories are added; this
# script does not vendor them.
# ---------------------------------------------------------------
declare -A REFS
REFS[h2o]="FMInference/H2O@27c47bc"          # NeurIPS 2023 release
REFS[snapkv]="FasterDecoding/SnapKV@ff9f9b1" # NeurIPS 2024 release
REFS[quest]="mit-han-lab/Quest@9be5ed3"      # ICML 2024 release
# Streamingllm has a faithful in-tree port (sink+window) so it
# isn't re-run with an upstream commit.

cat > "$OUT_DIR/upstream_commits.json" <<JSON
{
  "h2o":     "${REFS[h2o]}",
  "snapkv":  "${REFS[snapkv]}",
  "quest":   "${REFS[quest]}",
  "rationale": "Public-reference baseline parity for §VI.F vLLM SLO sweep. Pinned per the original publications' release commit.",
  "status_when_no_gpu": "HARNESS_READY_AWAITING_GPU_RUN",
  "queued_in": "todo_atc.md (R15-C / R17-C)"
}
JSON
echo "[parity] pinned upstream commits → $OUT_DIR/upstream_commits.json"

# ---------------------------------------------------------------
# Pre-flight check: CUDA + upstream policy artifacts. The script
# emits a harness-status stub unless BOTH are present.
# ---------------------------------------------------------------
if ! python - <<'PY'
import sys
try:
    import torch
    if not torch.cuda.is_available():
        sys.exit(1)
    # Upstream artifact registration check: the parity sweep
    # expects {h2o,snapkv,quest}_official to be registered in
    # seer.policy. The in-tree baselines don't claim parity.
    from seer.policy import build_policy  # noqa: F401
    # Smoke-detect: do the _official policy names exist?
    import experiments.eF_mixed_slo.driver_edf as drv  # noqa: F401
    # Inspect the argparse choices for `--policy`.
    import inspect, re
    src = inspect.getsource(drv)
    m = re.search(r"choices=\\(([^)]+)\\)", src)
    has_official = "_official" in (m.group(1) if m else "")
    sys.exit(0 if has_official else 1)
except Exception:
    sys.exit(2)
PY
then
    cat > "$OUT_DIR/parity_status.tex" <<'TEX'
% Auto-generated by baseline_parity_harness.sh (R17, harness-only).
\begin{tabular}{ll}
\toprule
Field & Value \\
\midrule
Status & \textsc{harness-only} (no CUDA) \\
H2O ref. & FMInference/H2O \\
SnapKV ref. & FasterDecoding/SnapKV \\
Quest ref. & mit-han-lab/Quest \\
Sweep & 6-way $\rho$/$D$ grid as in §VI.F \\
Queued in & \texttt{todo\_atc.md}~R15-C \\
\bottomrule
\end{tabular}
TEX
    echo "[parity] STATUS: no CUDA; emitted parity_status.tex"
    exit 0
fi

# ---------------------------------------------------------------
# GPU branch: actually run the upstream baselines + the §VI.F
# sweep. Requires datasets, transformers, and either submodules
# or PYTHONPATH pointing at cloned upstream repos.
# ---------------------------------------------------------------
SEEDS="${SEEDS:-0 1 2}"
NUM_PROMPTS="${NUM_PROMPTS:-24}"

for policy in h2o_official snapkv_official quest_official; do
    for seed in $SEEDS; do
        echo "[parity] running policy=$policy seed=$seed"
        python -m experiments.eF_mixed_slo.driver_edf \
            --policy "$policy" \
            --num_prompts "$NUM_PROMPTS" \
            --seed "$seed" \
            --out_dir "$OUT_DIR"
    done
done

# Aggregate into the §VI.F SLO-sweep / mechanism-counter format.
python -m experiments.eF_mixed_slo.scripts.aggregate_multiturn \
    --results_dir "$OUT_DIR" \
    --out "$OUT_DIR/multiturn_summary.json"

# Emit a comparison TeX vs the in-tree implementations.
python - <<PY
import json, pathlib
ROOT = pathlib.Path("$OUT_DIR")
local = json.loads(pathlib.Path(
    "experiments/eF_mixed_slo/results_vllm_path_beta4_scaled/multiturn_summary.json"
).read_text())
parity = json.loads((ROOT / "multiturn_summary.json").read_text())

rows = []
for policy in ("h2o", "snapkv", "quest"):
    L = local["per_policy"].get(policy, {})
    P = parity["per_policy"].get(f"{policy}_official", {})
    rows.append((
        policy,
        L.get("chat_miss_mean", float("nan")),
        P.get("chat_miss_mean", float("nan")),
    ))
lines = ["% Auto-generated by baseline_parity_harness.sh (R17).",
         r"\begin{tabular}{lrr}",
         r"\toprule",
         r"Policy & In-tree chat-miss & Upstream-port chat-miss \\",
         r"\midrule"]
for policy, l, p in rows:
    lines.append(f"\\texttt{{{policy}}} & ${l:.4f}$ & ${p:.4f}$ \\\\")
lines += [r"\bottomrule", r"\end{tabular}"]
(ROOT / "parity_compare.tex").write_text("\n".join(lines) + "\n")
print(f"[parity] wrote {ROOT / 'parity_compare.tex'}")
PY

echo "[parity] complete; see $OUT_DIR/{multiturn_summary,parity_compare}.{json,tex}"
